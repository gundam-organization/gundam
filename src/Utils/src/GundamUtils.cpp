  void releaseUnusedMemory(){
#if defined(__APPLE__) && defined(__MACH__)
    // Null selects all zones; zero requests maximal pressure relief.
    malloc_zone_pressure_relief(nullptr, 0);
#elif defined(__GLIBC__)
    malloc_trim(0);
#endif
  }

  std::string getProcessMemoryUsageSummary(){
    // Query before formatting so allocations made by the stream do not affect
    // the allocator snapshot. These are independent, approximate snapshots.
    const auto residentBytes = GenericToolbox::getProcessMemoryUsage();
    size_t allocatedBytes{0};
    size_t footprintBytes{0};
    bool hasAllocatedBytes{false};
    bool hasFootprintBytes{false};

#if defined(__APPLE__) && defined(__MACH__)
    malloc_statistics_t allocatorInfo{};
    // A null zone aggregates all malloc zones, rather than only the default.
    malloc_zone_statistics(nullptr, &allocatorInfo);
    allocatedBytes = allocatorInfo.size_in_use;
    hasAllocatedBytes = true;

    task_vm_info_data_t taskInfo{};
    mach_msg_type_number_t count = TASK_VM_INFO_COUNT;
    if( task_info(mach_task_self(), TASK_VM_INFO,
                  reinterpret_cast<task_info_t>(&taskInfo), &count) == KERN_SUCCESS
        and count >= TASK_VM_INFO_REV1_COUNT ){
      footprintBytes = taskInfo.phys_footprint;
      hasFootprintBytes = true;
    }
#elif defined(__GLIBC__) && defined(__GLIBC_PREREQ)
#if __GLIBC_PREREQ(2, 33)
    const auto allocatorInfo = mallinfo2();
    // Include malloc's large mmap-backed allocations, not just its arenas.
    allocatedBytes = allocatorInfo.uordblks + allocatorInfo.hblkhd;
    hasAllocatedBytes = true;
#endif
#endif

    auto formatMemorySize = [](size_t bytes_){
      const char* units[]{"B", "KB", "MB", "GB", "TB", "PB", "EB"};
      double value = double(bytes_);
      size_t unitIndex{0};
      while( value >= 1000. and unitIndex < 6 ){
        value /= 1000.;
        ++unitIndex;
      }
      std::stringstream formatted;
      formatted << std::fixed << std::setprecision(2) << value << units[unitIndex];
      return formatted.str();
    };

    std::stringstream summary;
    summary << "(" << formatMemorySize(residentBytes) << " RSS";
    if( hasAllocatedBytes ){
      summary << " / " << formatMemorySize(allocatedBytes) << " Alloc";
    }
    if( hasFootprintBytes ){
      summary << " / " << formatMemorySize(footprintBytes) << " Footprint";
    }
    summary << ")";
    return summary.str();
  }

